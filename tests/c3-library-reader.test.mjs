// C3-R27 — consistent library-pair reader tests. Isolated temporary fixtures only; no real library,
// Cloudflare or production file is read. Run with: node --test tests/c3-library-reader.test.mjs
import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import crypto from 'node:crypto';
import { inspectLibraryPair, assertDistinctTargets } from '../infrastructure/c3/library/library-pair-reader.mjs';
import {
  JOURNAL_NAME, LOCK_NAME, assertTargetsApproved,
} from '../infrastructure/c3/library/library-pair-recovery.mjs';

const TARGETS = ['specs/asset-library.json', 'specs/asset-library.generated.js'];
const VALUE = {
  version: 1,
  generation: 'gen-0001',
  assets: [{ id: 'a1', name: 'one' }, { id: 'a2', name: 'two' }],
};

function makeRoot(t) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'c3-r27-'));
  fs.mkdirSync(path.join(root, 'specs'), { recursive: true });
  t.after(() => fs.rmSync(root, { recursive: true, force: true }));
  return root;
}

// The generated module is a byte-exact format contract; this reproduces the generator's output.
function moduleText(value) {
  return [
    '// Generated by scripts/validate-asset-library.mjs from specs/asset-library.json.',
    '// Do not edit by hand: run `node scripts/validate-asset-library.mjs --build`.',
    `const library = ${JSON.stringify(value, null, 2)};`,
    '', 'export default library;', '',
  ].join('\n');
}

function writePair(root, value = VALUE) {
  fs.writeFileSync(path.join(root, TARGETS[0]), JSON.stringify(value, null, 2));
  fs.writeFileSync(path.join(root, TARGETS[1]), moduleText(value));
}

function read(root, targets = TARGETS) {
  return inspectLibraryPair({ rootDir: root, allowedTargets: targets });
}

function snapshot(root) {
  const out = [];
  const walk = (dir) => {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const abs = path.join(dir, entry.name);
      if (entry.isDirectory()) { out.push(['d', path.relative(root, abs)]); walk(abs); }
      else { const s = fs.statSync(abs); out.push(['f', path.relative(root, abs), s.size, s.mtimeMs]); }
    }
  };
  walk(root);
  return out.sort((a, b) => String(a[1]).localeCompare(String(b[1])));
}

const sha = (b) => crypto.createHash('sha256').update(b).digest('hex');

test('1. valid consistent pair is read successfully', (t) => {
  const root = makeRoot(t);
  writePair(root);
  const result = read(root);
  assert.equal(result.ok, true);
  assert.equal(result.reason, null);
  assert.equal(result.assetCount, 2);
  assert.equal(result.hashes.length, 2);
  for (const entry of result.hashes) assert.match(entry.sha256, /^[a-f0-9]{64}$/);
  assert.equal(result.hashes[0].sha256, sha(fs.readFileSync(path.join(root, TARGETS[0]))));
});

test('2. missing first or second file is rejected', (t) => {
  const root = makeRoot(t);
  writePair(root);
  fs.rmSync(path.join(root, TARGETS[0]));
  assert.equal(read(root).reason, 'R19_MISSING_OR_SYMLINK');
  writePair(root);
  fs.rmSync(path.join(root, TARGETS[1]));
  assert.equal(read(root).reason, 'R19_MISSING_OR_SYMLINK');
});

test('2b. absent root and non-string root are rejected without throwing', (t) => {
  const root = makeRoot(t);
  assert.deepEqual(inspectLibraryPair(), { ok: false, reason: 'R19_ROOT_REQUIRED' });
  assert.equal(read(path.join(root, 'does-not-exist')).reason, 'R19_ROOT_UNAVAILABLE');
});

test('3. malformed JSON or module content is rejected', (t) => {
  const root = makeRoot(t);
  writePair(root);
  fs.writeFileSync(path.join(root, TARGETS[0]), '{ this is not json');
  assert.equal(read(root).reason, 'R19_INVALID_DOCUMENT');
  writePair(root);
  fs.writeFileSync(path.join(root, TARGETS[1]), 'export default {};\n');
  assert.equal(read(root).reason, 'R19_INVALID_DOCUMENT');
});

test('4. mismatched generation identifiers are rejected', (t) => {
  const root = makeRoot(t);
  const other = { ...VALUE, generation: 'gen-0002' };
  fs.writeFileSync(path.join(root, TARGETS[0]), JSON.stringify(VALUE, null, 2));
  fs.writeFileSync(path.join(root, TARGETS[1]), moduleText(other));
  assert.equal(read(root).reason, 'R19_LIBRARY_MISMATCH');
});

test('5. hostile append after the expected export is rejected', (t) => {
  const root = makeRoot(t);
  writePair(root);
  fs.writeFileSync(path.join(root, TARGETS[1]), `${moduleText(VALUE)}\nconsole.log('unexpected');\n`);
  assert.equal(read(root).reason, 'R19_INVALID_DOCUMENT', 'the exact-byte contract must catch appended code');
});

test('6. noncanonical module bytes rejected; JSON formatting is not part of the contract', (t) => {
  const root = makeRoot(t);
  writePair(root);
  fs.writeFileSync(path.join(root, TARGETS[1]), moduleText(VALUE).replaceAll('  ', '    '));
  assert.equal(read(root).reason, 'R19_INVALID_DOCUMENT', 're-indented module must fail');
  writePair(root);
  fs.writeFileSync(path.join(root, TARGETS[1]), moduleText(VALUE).replace(/\n$/, ''));
  assert.equal(read(root).reason, 'R19_INVALID_DOCUMENT', 'missing trailing newline must fail');
  writePair(root);
  fs.writeFileSync(path.join(root, TARGETS[0]), JSON.stringify(VALUE));
  assert.equal(read(root).ok, true, 'compact JSON must still pass: the contract compares structure, not bytes');
});

test('7. pending journal and existing writer lock are both refused', (t) => {
  const root = makeRoot(t);
  writePair(root);
  fs.writeFileSync(path.join(root, 'specs', JOURNAL_NAME), '{"version":1}');
  assert.equal(read(root).reason, 'R19_PENDING_JOURNAL');
  fs.rmSync(path.join(root, 'specs', JOURNAL_NAME));
  fs.writeFileSync(path.join(root, 'specs', LOCK_NAME), 'lock');
  assert.equal(read(root).reason, 'R19_WRITER_LOCK_PRESENT');
  fs.writeFileSync(path.join(root, 'specs', JOURNAL_NAME), '{"version":1}');
  assert.equal(read(root).reason, 'R19_PENDING_JOURNAL', 'journal takes precedence when both exist');
});

test('8-9. explicit target authorization: no implicit fallback, no bypass', (t) => {
  const root = makeRoot(t);
  writePair(root);
  // A perfectly valid pair on disk is still refused without an approved list.
  assert.equal(inspectLibraryPair({ rootDir: root }).reason, 'R19_TARGETS_NOT_APPROVED');
  assert.equal(read(root, []).reason, 'R19_TARGETS_NOT_APPROVED');
  assert.equal(read(root, ['/etc/passwd', 'specs/x.json']).reason, 'R19_TARGETS_NOT_APPROVED');
  assert.equal(read(root, ['specs/../../escape.json', 'specs/asset-library.json']).reason, 'R19_TARGETS_NOT_APPROVED');
  assert.equal(read(root, [TARGETS[0], TARGETS[0]]).reason, 'R19_TARGETS_NOT_APPROVED');
  // Nesting is not a pair.
  assert.throws(() => assertDistinctTargets(['specs', 'specs/asset-library.json']), /R19_TARGET_CONFLICT/);
  assert.equal(read(root, ['specs', 'specs/asset-library.json']).reason, 'R19_TARGETS_NOT_APPROVED');
});

test('10. path traversal and realpath escape are refused', (t) => {
  const root = makeRoot(t);
  writePair(root);
  const outside = fs.mkdtempSync(path.join(os.tmpdir(), 'c3-r27-outside-'));
  t.after(() => fs.rmSync(outside, { recursive: true, force: true }));
  fs.writeFileSync(path.join(outside, 'asset-library.json'), JSON.stringify(VALUE, null, 2));
  try {
    fs.symlinkSync(outside, path.join(root, 'inner'), 'junction');
  } catch {
    t.skip('platform cannot create a directory link');
    return;
  }
  const result = inspectLibraryPair({
    rootDir: root, allowedTargets: ['inner/asset-library.json', TARGETS[1]],
  });
  assert.equal(result.reason, 'R19_PATH_ESCAPE');
});

test('11. symlink target is refused (skips only when the host cannot create symlinks)', (t) => {
  const root = makeRoot(t);
  writePair(root);
  const real = path.join(root, 'specs', 'real.json');
  fs.writeFileSync(real, JSON.stringify(VALUE, null, 2));
  const linkPath = path.join(root, TARGETS[0]);
  // Fixture fix: writePair() already created this path, so a symlink over it fails with EEXIST — which the
  // previous broad catch reported as "host refuses symlinks". Remove the occupying file first; that was the
  // only reason this case skipped on Linux, where symlink creation is permitted.
  fs.rmSync(linkPath);
  try {
    fs.symlinkSync(real, linkPath, 'file');
  } catch (error) {
    // Skip ONLY for genuine platform capability limits. Anything else (EEXIST, ENOENT, ...) is a real
    // failure of the fixture or the code under test and must not be laundered into a skip.
    if (['EPERM', 'EACCES', 'ENOSYS', 'ENOTSUP', 'EOPNOTSUPP'].includes(error.code)) {
      t.skip(`host refuses file symlinks without elevation (${error.code})`);
      return;
    }
    throw error;
  }
  // Guard against a silent non-symlink so the assertion below cannot pass trivially.
  assert.equal(fs.lstatSync(linkPath).isSymbolicLink(), true, 'fixture must create a real symlink');
  assert.equal(read(root).reason, 'R19_MISSING_OR_SYMLINK');
});

test('12-13. no automatic recovery and no filesystem mutation on any path', (t) => {
  const root = makeRoot(t);
  writePair(root);
  fs.writeFileSync(path.join(root, 'specs', JOURNAL_NAME), JSON.stringify({ version: 1 }));
  fs.writeFileSync(path.join(root, `${TARGETS[0]}.r16-new-deadbeefdeadbeef`), 'staged');
  fs.writeFileSync(path.join(root, `${TARGETS[0]}.r16-backup-deadbeefdeadbeef`), 'backup');
  const before = snapshot(root);
  const result = read(root);
  assert.equal(result.reason, 'R19_PENDING_JOURNAL');
  assert.deepEqual(snapshot(root), before, 'a pending journal must not be consumed or repaired');
  // Success path must also be side-effect free.
  fs.rmSync(path.join(root, 'specs', JOURNAL_NAME));
  const clean = snapshot(root);
  assert.equal(read(root).ok, true);
  assert.deepEqual(snapshot(root), clean, 'a successful read must not create or modify anything');
});

test('14. repeated reads are deterministic', (t) => {
  const root = makeRoot(t);
  writePair(root);
  const first = read(root);
  const second = read(root);
  const third = read(root);
  assert.deepEqual(second, first);
  assert.deepEqual(third, first);
});

test('15. interoperability with the recovery module authorization', (t) => {
  const root = makeRoot(t);
  writePair(root);
  // The reader accepts exactly what the recovery module approves.
  const approved = assertTargetsApproved(TARGETS);
  assert.equal(inspectLibraryPair({ rootDir: root, allowedTargets: approved }).ok, true);
  // And refuses what it refuses, with its own reason code.
  assert.throws(() => assertTargetsApproved(['../escape']), /R17_TARGETS_NOT_APPROVED/);
  assert.equal(read(root, ['../escape', TARGETS[1]]).reason, 'R19_TARGETS_NOT_APPROVED');
});

test('16. partially completed transaction is refused, not repaired', (t) => {
  const root = makeRoot(t);
  writePair(root);
  const staged = path.join(root, `${TARGETS[0]}.r16-new-0123456789abcdef`);
  const backup = path.join(root, `${TARGETS[0]}.r16-backup-0123456789abcdef`);
  fs.writeFileSync(staged, 'half-written');
  fs.writeFileSync(backup, 'old-content');
  fs.writeFileSync(path.join(root, 'specs', JOURNAL_NAME), JSON.stringify({ version: 1, nonce: '0123456789abcdef', entries: [] }));
  const before = snapshot(root);
  assert.equal(read(root).reason, 'R19_PENDING_JOURNAL');
  assert.equal(fs.readFileSync(staged, 'utf8'), 'half-written');
  assert.equal(fs.readFileSync(backup, 'utf8'), 'old-content');
  assert.deepEqual(snapshot(root), before);
});
