// C3-R28 — target policy and immutable library generation tests. Disposable temporary fixtures only.
// Run with: node --test tests/c3-library-generation.test.mjs
import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import crypto from 'node:crypto';
import {
  createTargetPolicy, assertPolicy, assertDestinationInsidePolicy, TARGET_TIERS,
} from '../infrastructure/c3/library/target-policy.mjs';
import {
  describeGeneration, verifyGeneration, materializeGeneration, assertMatchingGeneration,
} from '../infrastructure/c3/library/library-generation-r20.mjs';
import { inspectLibraryPair } from '../infrastructure/c3/library/library-pair-reader.mjs';
import { assertTargetsApproved } from '../infrastructure/c3/library/library-pair-recovery.mjs';

const TARGETS = ['specs/asset-library.json', 'specs/asset-library.generated.js'];
const VALUE = { version: 1, generation: 'gen-0001', assets: [{ id: 'a1' }, { id: 'a2' }] };

const moduleText = (value) => [
  '// Generated by scripts/validate-asset-library.mjs from specs/asset-library.json.',
  '// Do not edit by hand: run `node scripts/validate-asset-library.mjs --build`.',
  `const library = ${JSON.stringify(value, null, 2)};`,
  '', 'export default library;', '',
].join('\n');

function tmp(t, prefix = 'c3-r28-') {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), prefix));
  t.after(() => fs.rmSync(dir, { recursive: true, force: true }));
  return dir;
}

// A valid, reader-compatible source library pair.
function makeSource(t) {
  const root = tmp(t, 'c3-r28-src-');
  fs.mkdirSync(path.join(root, 'specs'), { recursive: true });
  fs.writeFileSync(path.join(root, TARGETS[0]), JSON.stringify(VALUE, null, 2));
  fs.writeFileSync(path.join(root, TARGETS[1]), moduleText(VALUE));
  return root;
}

function makeOutputAndPolicy(t) {
  const outputRoot = tmp(t, 'c3-r28-out-');
  const policy = createTargetPolicy({ tier: TARGET_TIERS.TEMPORARY, rootDir: outputRoot, targets: TARGETS });
  return { outputRoot, policy };
}

const sha = (b) => crypto.createHash('sha256').update(b).digest('hex');

function snapshot(root) {
  const out = [];
  const walk = (dir) => {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const abs = path.join(dir, entry.name);
      if (entry.isDirectory()) { out.push(['d', path.relative(root, abs)]); walk(abs); }
      else { const s = fs.statSync(abs); out.push(['f', path.relative(root, abs), s.size, s.mtimeMs]); }
    }
  };
  walk(root);
  return out.sort((a, b) => String(a[1]).localeCompare(String(b[1])));
}

test('1. valid content-addressed generation is created in scratch storage', (t) => {
  const sourceRoot = makeSource(t);
  const { outputRoot, policy } = makeOutputAndPolicy(t);
  const result = materializeGeneration({ policy, sourceRoot, outputRoot, enabled: true });

  assert.equal(result.created, true);
  assert.equal(path.basename(result.output), `sha256-${result.generationId}`);
  const record = JSON.parse(fs.readFileSync(path.join(result.output, 'generation.json'), 'utf8'));
  assert.equal(record.schema, 'alp-c3-r20-generation-v1');
  assert.equal(record.publicationAuthorized, false, 'a generation never authorizes publication');
  assert.deepEqual(Object.keys(record.sourceHashes).sort(), [...TARGETS].sort());
  for (const target of TARGETS) {
    assert.equal(sha(fs.readFileSync(path.join(result.output, target))), record.sourceHashes[target]);
  }
  const verified = verifyGeneration({ generationDir: result.output, allowedTargets: TARGETS });
  assert.deepEqual(verified, { ok: true, generationId: result.generationId, hashes: record.sourceHashes });
});

test('2. identifiers are deterministic and re-materializing reuses the identical generation', (t) => {
  const sourceRoot = makeSource(t);
  const { outputRoot, policy } = makeOutputAndPolicy(t);
  const first = describeGeneration({ sourceRoot, allowedTargets: TARGETS });
  const second = describeGeneration({ sourceRoot, allowedTargets: TARGETS });
  assert.equal(first.generationId, second.generationId);
  assert.match(first.generationId, /^[a-f0-9]{64}$/);

  const made = materializeGeneration({ policy, sourceRoot, outputRoot, enabled: true });
  assert.equal(made.created, true);
  assert.equal(made.generationId, first.generationId);
  const again = materializeGeneration({ policy, sourceRoot, outputRoot, enabled: true });
  assert.equal(again.created, false, 'an identical existing generation must be reused, not rewritten');
  assert.equal(again.generationId, made.generationId);
});

test('3. tampered artifact bytes and manifest hashes are detected', (t) => {
  const sourceRoot = makeSource(t);
  const { outputRoot, policy } = makeOutputAndPolicy(t);
  const made = materializeGeneration({ policy, sourceRoot, outputRoot, enabled: true });

  const target = path.join(made.output, TARGETS[0]);
  const original = fs.readFileSync(target);
  fs.writeFileSync(target, 'tampered');
  assert.match(verifyGeneration({ generationDir: made.output, allowedTargets: TARGETS }).reason, /R20_TAMPERED/);
  fs.writeFileSync(target, original);
  assert.equal(verifyGeneration({ generationDir: made.output, allowedTargets: TARGETS }).ok, true);

  const manifestPath = path.join(made.output, 'generation.json');
  const record = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
  record.sourceHashes[TARGETS[0]] = 'f'.repeat(64);
  fs.writeFileSync(manifestPath, JSON.stringify(record, null, 2));
  assert.match(verifyGeneration({ generationDir: made.output, allowedTargets: TARGETS }).reason, /R20_TAMPERED|R20_ID_MISMATCH/);
});

test('3b. generation id cannot be forged by editing the manifest', (t) => {
  const sourceRoot = makeSource(t);
  const { outputRoot, policy } = makeOutputAndPolicy(t);
  const made = materializeGeneration({ policy, sourceRoot, outputRoot, enabled: true });
  const manifestPath = path.join(made.output, 'generation.json');
  const record = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
  record.generationId = 'a'.repeat(64);
  fs.writeFileSync(manifestPath, JSON.stringify(record, null, 2));
  assert.match(verifyGeneration({ generationDir: made.output, allowedTargets: TARGETS }).reason, /R20_INVALID_MANIFEST/);
});

test('4. a conflicting existing generation is never overwritten', (t) => {
  const sourceRoot = makeSource(t);
  const { outputRoot, policy } = makeOutputAndPolicy(t);
  const { generationId } = describeGeneration({ sourceRoot, allowedTargets: TARGETS });
  const destination = path.join(outputRoot, `sha256-${generationId}`);
  fs.mkdirSync(destination, { recursive: true });
  fs.writeFileSync(path.join(destination, 'generation.json'), JSON.stringify({ schema: 'something-else' }));

  assert.throws(
    () => materializeGeneration({ policy, sourceRoot, outputRoot, enabled: true }),
    /R20_IMMUTABLE_COLLISION/,
  );
  assert.equal(
    JSON.parse(fs.readFileSync(path.join(destination, 'generation.json'), 'utf8')).schema,
    'something-else',
    'the pre-existing content must be left exactly as it was',
  );
});

test('5. incomplete generations fail verification', (t) => {
  const sourceRoot = makeSource(t);
  const { outputRoot, policy } = makeOutputAndPolicy(t);
  const made = materializeGeneration({ policy, sourceRoot, outputRoot, enabled: true });

  fs.rmSync(path.join(made.output, TARGETS[1]));
  assert.equal(verifyGeneration({ generationDir: made.output, allowedTargets: TARGETS }).ok, false);

  const manifestPath = path.join(made.output, 'generation.json');
  fs.rmSync(manifestPath);
  assert.equal(verifyGeneration({ generationDir: made.output, allowedTargets: TARGETS }).ok, false);
  assert.equal(verifyGeneration({ generationDir: made.output }).ok, false, 'verification without a target set fails closed');
});

test('6. invalid roots and policies are refused', (t) => {
  const sourceRoot = makeSource(t);
  const outputRoot = tmp(t, 'c3-r28-out-');
  const outside = tmp(t, 'c3-r28-outside-');

  // Tier separation: only temporary is issuable in C3-R28.
  assert.throws(() => createTargetPolicy({ tier: 'production', rootDir: outputRoot, targets: TARGETS }), /R28_PRODUCTION_NOT_AUTHORIZED/);
  assert.throws(() => createTargetPolicy({ tier: 'staging', rootDir: outputRoot, targets: TARGETS }), /R28_STAGING_NOT_AUTHORIZED/);
  assert.throws(() => createTargetPolicy({ tier: 'whatever', rootDir: outputRoot, targets: TARGETS }), /R28_POLICY_TIER_UNKNOWN/);
  // A root outside the OS temp directory can never be authorised.
  assert.throws(() => createTargetPolicy({ tier: 'temporary', rootDir: process.cwd(), targets: TARGETS }), /R28_ROOT_NOT_TEMPORARY/);
  assert.throws(() => createTargetPolicy({ tier: 'temporary', rootDir: outputRoot, targets: [] }), /R17_TARGETS_NOT_APPROVED/);
  assert.throws(() => createTargetPolicy({ tier: 'temporary', rootDir: outputRoot }), /R17_TARGETS_NOT_APPROVED/);

  // A forged policy object is re-validated from its values, not trusted.
  const forged = { tier: 'temporary', rootDir: process.cwd(), targets: TARGETS, publicationAuthorized: false };
  assert.throws(() => assertPolicy(forged), /R28_ROOT_NOT_TEMPORARY/);
  const forgedFlag = { tier: 'temporary', rootDir: outputRoot, targets: TARGETS, publicationAuthorized: true };
  assert.throws(() => assertPolicy(forgedFlag), /R28_PUBLICATION_FLAG_INVALID/);

  const policy = createTargetPolicy({ tier: TARGET_TIERS.TEMPORARY, rootDir: outputRoot, targets: TARGETS });
  assert.throws(() => assertDestinationInsidePolicy(policy, outside), /R28_DESTINATION_OUTSIDE_POLICY/);
  assert.equal(assertDestinationInsidePolicy(policy, outputRoot), fs.realpathSync(outputRoot));
  // Nothing was written by any refusal above.
  assert.deepEqual(fs.readdirSync(outputRoot), []);
  assert.deepEqual(fs.readdirSync(sourceRoot).sort(), ['specs']);
});

test('7. traversal, nesting and out-of-scope destinations are refused', (t) => {
  const sourceRoot = makeSource(t);
  const { outputRoot, policy } = makeOutputAndPolicy(t);
  const otherTemp = tmp(t, 'c3-r28-other-');

  assert.throws(() => createTargetPolicy({ tier: 'temporary', rootDir: outputRoot, targets: ['specs/../../escape.json', TARGETS[1]] }), /R17_TARGETS_NOT_APPROVED/);
  assert.throws(() => createTargetPolicy({ tier: 'temporary', rootDir: outputRoot, targets: ['C:\\Windows\\system32', TARGETS[1]] }), /R17_TARGETS_NOT_APPROVED/);
  assert.throws(() => createTargetPolicy({ tier: 'temporary', rootDir: outputRoot, targets: ['specs', TARGETS[0]] }), /R19_TARGET_CONFLICT/);

  // Output must be scratch AND inside the authorised root.
  assert.throws(() => materializeGeneration({ policy, sourceRoot, outputRoot: process.cwd(), enabled: true }), /R20_OUTPUT_NOT_SCRATCH/);
  assert.throws(() => materializeGeneration({ policy, sourceRoot, outputRoot: otherTemp, enabled: true }), /R20_OUTPUT_OUTSIDE_POLICY/);
  assert.deepEqual(fs.readdirSync(otherTemp), [], 'a refused destination must be untouched');
});

test('8a. junction escape from the policy root is refused', (t) => {
  const sourceRoot = makeSource(t);
  const outputRoot = tmp(t, 'c3-r28-out-');
  const policy = createTargetPolicy({ tier: TARGET_TIERS.TEMPORARY, rootDir: outputRoot, targets: TARGETS });
  const outside = tmp(t, 'c3-r28-outside-');
  try {
    fs.symlinkSync(outside, path.join(outputRoot, 'link'), 'junction');
  } catch {
    t.skip('host cannot create a directory link');
    return;
  }
  assert.throws(
    () => materializeGeneration({ policy, sourceRoot, outputRoot: path.join(outputRoot, 'link'), enabled: true }),
    /R20_OUTPUT_OUTSIDE_POLICY/,
    'a linked output directory resolving outside the policy root must be refused',
  );
});

test('8b. symlinked generation manifest is refused', (t) => {
  const sourceRoot = makeSource(t);
  const { outputRoot, policy } = makeOutputAndPolicy(t);
  const outside = tmp(t, 'c3-r28-outside-');
  const made = materializeGeneration({ policy, sourceRoot, outputRoot, enabled: true });
  const manifestPath = path.join(made.output, 'generation.json');
  const realManifest = path.join(outside, 'real-generation.json');
  fs.copyFileSync(manifestPath, realManifest);
  fs.rmSync(manifestPath);
  try {
    fs.symlinkSync(realManifest, manifestPath, 'file');
  } catch {
    t.skip('host refuses file symlinks without elevation; R20_SYMLINK not exercised here');
    return;
  }
  assert.match(verifyGeneration({ generationDir: made.output, allowedTargets: TARGETS }).reason, /R20_SYMLINK/);
});

test('9. no unintended filesystem mutations and no staging leftovers', (t) => {
  const sourceRoot = makeSource(t);
  const { outputRoot, policy } = makeOutputAndPolicy(t);
  const sourceBefore = snapshot(sourceRoot);

  materializeGeneration({ policy, sourceRoot, outputRoot, enabled: true });
  materializeGeneration({ policy, sourceRoot, outputRoot, enabled: true });

  assert.deepEqual(snapshot(sourceRoot), sourceBefore, 'generation must not modify the source workspace');
  const entries = fs.readdirSync(outputRoot);
  assert.equal(entries.length, 1, `expected exactly one generation directory, saw ${entries.join(', ')}`);
  assert.equal(entries[0].startsWith('sha256-'), true);
  assert.equal(entries.some((name) => name.startsWith('.r20-staging-')), false, 'staging directories must not survive');
});

test('10. publication is never authorised by a successful generation', (t) => {
  const sourceRoot = makeSource(t);
  const { outputRoot, policy } = makeOutputAndPolicy(t);

  assert.throws(() => materializeGeneration({ policy, sourceRoot, outputRoot }), /R20_DISABLED/);
  assert.throws(() => materializeGeneration({ policy, sourceRoot, outputRoot, enabled: false }), /R20_DISABLED/);
  assert.deepEqual(fs.readdirSync(outputRoot), [], 'a disabled call must write nothing');

  const made = materializeGeneration({ policy, sourceRoot, outputRoot, enabled: true });
  const record = JSON.parse(fs.readFileSync(path.join(made.output, 'generation.json'), 'utf8'));
  assert.equal(record.publicationAuthorized, false);
  assert.equal(Object.prototype.hasOwnProperty.call(made, 'published'), false);
  assert.equal(Object.prototype.hasOwnProperty.call(made, 'url'), false);
});

test('11. interoperability with R26 and R27, and paired-generation matching', (t) => {
  const sourceRoot = makeSource(t);
  const { outputRoot, policy } = makeOutputAndPolicy(t);

  // R27 accepts the same pair the generator reads.
  assert.equal(inspectLibraryPair({ rootDir: sourceRoot, allowedTargets: TARGETS }).ok, true);
  // R26 authorization governs the policy's target set.
  assert.deepEqual([...assertTargetsApproved(TARGETS)], TARGETS);

  // A target set the reader refuses must stop generation, not be worked around.
  assert.throws(
    () => describeGeneration({ sourceRoot, allowedTargets: ['specs/other.json', TARGETS[1]] }),
    /R20_SOURCE_UNSAFE:R19_MISSING_OR_SYMLINK/,
  );
  // A pending transaction in the source is reported, never repaired.
  const journal = path.join(sourceRoot, 'specs', '.c3-r17-library-journal.json');
  fs.writeFileSync(journal, '{}');
  assert.throws(() => describeGeneration({ sourceRoot, allowedTargets: TARGETS }), /R20_SOURCE_UNSAFE:R19_PENDING_JOURNAL/);
  assert.equal(fs.existsSync(journal), true, 'the journal must not be consumed');
  fs.rmSync(journal);

  const made = materializeGeneration({ policy, sourceRoot, outputRoot, enabled: true });
  assert.equal(assertMatchingGeneration({ catalogDir: made.output, workerDir: made.output, allowedTargets: TARGETS }).ok, true);

  // A second, different source yields a different generation; pairing them must fail.
  const otherSource = makeSource(t);
  const changed = { ...VALUE, generation: 'gen-0009' };
  fs.writeFileSync(path.join(otherSource, TARGETS[0]), JSON.stringify(changed, null, 2));
  fs.writeFileSync(path.join(otherSource, TARGETS[1]), moduleText(changed));
  const second = materializeGeneration({ policy, sourceRoot: otherSource, outputRoot, enabled: true });
  assert.notEqual(second.generationId, made.generationId);
  assert.deepEqual(
    assertMatchingGeneration({ catalogDir: made.output, workerDir: second.output, allowedTargets: TARGETS }),
    { ok: false, reason: 'R20_GENERATION_MISMATCH' },
  );
});
