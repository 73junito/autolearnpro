// C3-R31 — offline artifact evidence verification tests.
// ALL FIXTURES ARE SYNTHETIC TEST DATA. Passing these tests is NOT evidence that a catalog or Worker build
// ever succeeded; no bundler runs and no application exists.
// Run with: node --test tests/c3-offline-evidence.test.mjs
import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import crypto from 'node:crypto';
import {
  artifactDigest, sourceSnapshot, verifyOfflineEvidence,
  SOURCE_SNAPSHOT_INPUTS, SOURCE_SNAPSHOT_DIRS, EVIDENCE_CLAIMS,
} from '../infrastructure/c3/build/offline-evidence-r22.mjs';
import { createTargetPolicy, TARGET_TIERS } from '../infrastructure/c3/library/target-policy.mjs';
import { materializeGeneration } from '../infrastructure/c3/library/library-generation-r20.mjs';
import { proposeBuildAttestation, verifyBuildPair } from '../infrastructure/c3/library/build-provenance-r21.mjs';

const TARGETS = ['specs/asset-library.json', 'specs/asset-library.generated.js'];
const VALUE = { version: 1, generation: 'gen-0001', assets: [{ id: 'a1' }] };
const SNAPSHOT_COMMIT = 'e'.repeat(64);

const moduleText = (value) => [
  '// Generated by scripts/validate-asset-library.mjs from specs/asset-library.json.',
  '// Do not edit by hand: run `node scripts/validate-asset-library.mjs --build`.',
  `const library = ${JSON.stringify(value, null, 2)};`,
  '', 'export default library;', '',
].join('\n');

function tmp(t, prefix = 'c3-r31-') {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), prefix));
  t.after(() => fs.rmSync(dir, { recursive: true, force: true }));
  return dir;
}

const sha = (b) => crypto.createHash('sha256').update(b).digest('hex');

function snapshot(root) {
  const out = [];
  const walk = (dir) => {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const abs = path.join(dir, entry.name);
      if (entry.isDirectory()) { out.push(['d', path.relative(root, abs)]); walk(abs); }
      else { const s = fs.statSync(abs); out.push(['f', path.relative(root, abs), s.size, s.mtimeMs]); }
    }
  };
  walk(root);
  return out.sort((a, b) => String(a[1]).localeCompare(String(b[1])));
}

// Builds a complete synthetic evidence tree: source repo, artifact bytes, generation and evidence record.
function setupEvidence(t) {
  const policyRoot = tmp(t);
  const repo = path.join(policyRoot, 'repo');
  const out = path.join(policyRoot, 'out');
  fs.mkdirSync(path.join(repo, 'specs'), { recursive: true });
  fs.mkdirSync(out);
  fs.writeFileSync(path.join(repo, TARGETS[0]), JSON.stringify(VALUE, null, 2));
  fs.writeFileSync(path.join(repo, TARGETS[1]), moduleText(VALUE));
  // The nine inputs R22's snapshot contract requires (synthetic placeholders).
  for (const name of SOURCE_SNAPSHOT_INPUTS) {
    const abs = path.join(repo, name);
    fs.mkdirSync(path.dirname(abs), { recursive: true });
    fs.writeFileSync(abs, '{"synthetic":true}');
  }
  for (const dir of SOURCE_SNAPSHOT_DIRS) {
    fs.mkdirSync(path.join(repo, dir), { recursive: true });
    fs.writeFileSync(path.join(repo, dir, 'file.txt'), 'synthetic');
  }
  const policy = createTargetPolicy({ tier: TARGET_TIERS.TEMPORARY, rootDir: policyRoot, targets: TARGETS });

  fs.mkdirSync(path.join(out, 'generations'));
  const generation = materializeGeneration({
    policy, sourceRoot: repo, outputRoot: path.join(out, 'generations'), enabled: true,
  });

  fs.mkdirSync(path.join(out, 'catalog'));
  fs.writeFileSync(path.join(out, 'catalog', 'index.html'), '<html>synthetic catalog</html>');
  fs.writeFileSync(path.join(out, 'catalog', 'assets.js'), 'export const assets = [];');
  fs.mkdirSync(path.join(out, 'worker'));
  fs.writeFileSync(path.join(out, 'worker', 'worker.js'), 'export default {};');

  const catalogDigest = artifactDigest({ policy, directory: path.join(out, 'catalog') });
  const workerDigest = artifactDigest({ policy, directory: path.join(out, 'worker') });
  const catalogBuild = proposeBuildAttestation({
    policy, generationDir: generation.output, surface: 'catalog',
    buildId: 'test-catalog-1', sourceCommit: SNAPSHOT_COMMIT, artifactSha256: catalogDigest.sha256,
  });
  const workerBuild = proposeBuildAttestation({
    policy, generationDir: generation.output, surface: 'cloudflare-worker',
    buildId: 'test-worker-1', sourceCommit: SNAPSHOT_COMMIT, artifactSha256: workerDigest.sha256,
  });
  const pair = verifyBuildPair({ policy, generationDir: generation.output, catalog: catalogBuild, worker: workerBuild });
  assert.equal(pair.ok, true, 'fixture pair must be internally valid');

  const record = {
    schema: 'alp-c3-r22-offline-evidence-v1',
    generationId: generation.generationId,
    sourceSnapshotSha256: SNAPSHOT_COMMIT,
    sourceCommitVerified: false,
    ciAttested: false,
    catalog: { ...catalogDigest, build: catalogBuild },
    worker: { ...workerDigest, build: workerBuild },
    pairId: pair.pairId,
    publicationAuthorized: false,
  };
  const write = (value) => fs.writeFileSync(path.join(out, 'offline-evidence.json'), JSON.stringify(value, null, 2));
  write(record);
  return { policyRoot, policy, repo, out, record, write, generation, catalogDigest, workerDigest };
}

const verify = (env) => verifyOfflineEvidence({ policy: env.policy, outputRoot: env.out, allowedTargets: TARGETS });

test('1. valid supplied offline evidence verifies', (t) => {
  const env = setupEvidence(t);
  const result = verify(env);
  assert.equal(result.ok, true, result.reason);
  assert.equal(result.pairId, env.record.pairId);
  assert.equal(result.generationId, env.record.generationId);
});

test('2. recorded and independently recomputed digests agree', (t) => {
  const env = setupEvidence(t);
  const result = verify(env);
  assert.equal(result.digests.catalog.recorded, result.digests.catalog.recomputed);
  assert.equal(result.digests.worker.recorded, result.digests.worker.recomputed);
  assert.equal(result.digests.catalog.recomputed, env.catalogDigest.sha256);
  assert.ok(result.digests.fileCount >= 3);
});

test('3. modified artifact bytes are detected', (t) => {
  const env = setupEvidence(t);
  fs.appendFileSync(path.join(env.out, 'catalog', 'assets.js'), '/* tampered */');
  assert.deepEqual(verify(env), { ok: false, reason: 'R31_ARTIFACT_TAMPERED' });
});

test('4. missing artifacts are reported, not repaired', (t) => {
  const env = setupEvidence(t);
  fs.rmSync(path.join(env.out, 'worker'), { recursive: true });
  const result = verify(env);
  assert.equal(result.ok, false);
  assert.match(result.reason, /^R31_ARTIFACT_UNREADABLE:/);
  assert.equal(fs.existsSync(path.join(env.out, 'worker')), false, 'verification must not recreate artifacts');
});

test('5. malformed evidence records are refused', (t) => {
  const env = setupEvidence(t);
  env.write({ schema: 'something-else' });
  assert.deepEqual(verify(env), { ok: false, reason: 'R31_INVALID_SCHEMA' });
  env.write({ ...env.record, catalog: { files: [] } });
  assert.deepEqual(verify(env), { ok: false, reason: 'R31_INVALID_SHAPE' });
  fs.writeFileSync(path.join(env.out, 'offline-evidence.json'), '{ not json');
  assert.equal(verify(env).ok, false);
  fs.rmSync(path.join(env.out, 'offline-evidence.json'));
  assert.equal(verify(env).ok, false, 'absent evidence must fail closed');
});

test('6. invalid source snapshots are refused', (t) => {
  const env = setupEvidence(t);
  env.write({ ...env.record, sourceSnapshotSha256: 'f'.repeat(64) });
  assert.deepEqual(verify(env), { ok: false, reason: 'R31_SNAPSHOT_MISMATCH' });
  fs.rmSync(path.join(env.repo, 'vite.config.js'));
  assert.throws(() => sourceSnapshot({ policy: env.policy, rootDir: env.repo }), /R31_SOURCE_MISSING:vite\.config\.js/);
});

test('7-8. forged commit and CI claims are refused at both levels', (t) => {
  const env = setupEvidence(t);
  env.write({ ...env.record, sourceCommitVerified: true });
  assert.deepEqual(verify(env), { ok: false, reason: 'R31_INVALID_POLICY' });
  env.write({ ...env.record, ciAttested: true });
  assert.deepEqual(verify(env), { ok: false, reason: 'R31_INVALID_POLICY' });
  env.write({
    ...env.record,
    catalog: { ...env.record.catalog, build: { ...env.record.catalog.build, ciAttested: true } },
  });
  assert.deepEqual(verify(env), { ok: false, reason: 'R31_PAIR_MISMATCH' });
});

test('9. swapping catalog and Worker evidence is refused', (t) => {
  const env = setupEvidence(t);
  env.write({ ...env.record, catalog: env.record.worker, worker: env.record.catalog });
  assert.equal(verify(env).ok, false);
});

test('10. invalid temporary target policies are refused', (t) => {
  const env = setupEvidence(t);
  const noPolicy = verifyOfflineEvidence({ outputRoot: env.out, allowedTargets: TARGETS });
  assert.equal(noPolicy.ok, false);
  const forged = { tier: 'temporary', rootDir: process.cwd(), targets: TARGETS, publicationAuthorized: false };
  const forgedResult = verifyOfflineEvidence({ policy: forged, outputRoot: env.out, allowedTargets: TARGETS });
  assert.equal(forgedResult.ok, false);
  assert.match(forgedResult.reason, /R28_ROOT_NOT_TEMPORARY/);
  assert.throws(() => createTargetPolicy({ tier: 'staging', rootDir: env.policyRoot, targets: TARGETS }), /R28_STAGING_NOT_AUTHORIZED/);
});

test('11-12. traversal and realpath escape are refused', (t) => {
  const env = setupEvidence(t);
  const traversal = verifyOfflineEvidence({
    policy: env.policy, outputRoot: path.join(env.out, '..', '..', 'etc'), allowedTargets: TARGETS,
  });
  assert.equal(traversal.ok, false);

  const outside = tmp(t, 'c3-r31-outside-');
  const linked = path.join(env.policyRoot, 'linked-out');
  try {
    fs.symlinkSync(outside, linked, 'junction');
  } catch {
    t.skip('host cannot create a directory link');
    return;
  }
  const escaped = verifyOfflineEvidence({ policy: env.policy, outputRoot: linked, allowedTargets: TARGETS });
  assert.deepEqual(escaped, { ok: false, reason: 'R31_EVIDENCE_DIR_OUTSIDE_POLICY' });
});

test('13. symlinked artifacts are refused', (t) => {
  const env = setupEvidence(t);
  const outside = tmp(t, 'c3-r31-outside-');
  const realFile = path.join(outside, 'assets.js');
  fs.writeFileSync(realFile, 'export const assets = [];');
  const target = path.join(env.out, 'catalog', 'assets.js');
  fs.rmSync(target);
  try {
    fs.symlinkSync(realFile, target, 'file');
  } catch {
    t.skip('host refuses file symlinks without elevation');
    return;
  }
  const result = verify(env);
  assert.equal(result.ok, false);
  assert.match(result.reason, /R31_SYMLINK_OUTPUT/);
});

test('14. repeated verification is deterministic and side-effect free', (t) => {
  const env = setupEvidence(t);
  const before = snapshot(env.policyRoot);
  const first = verify(env);
  const second = verify(env);
  const third = verify(env);
  assert.deepEqual(second, first);
  assert.deepEqual(third, first);
  assert.deepEqual(snapshot(env.policyRoot), before, 'verification must not create or modify anything');
});

test('15. the module contains no bundler, subprocess, network or write call', () => {
  const source = fs.readFileSync('infrastructure/c3/build/offline-evidence-r22.mjs', 'utf8');
  const code = source.split('\n').filter((line) => !line.trimStart().startsWith('//')).join('\n');
  for (const banned of ["from 'vite'", "from 'esbuild'", 'child_process', 'execSync', 'spawn(', 'fetch(', 'http']) {
    assert.equal(code.includes(banned), false, `extracted module must not contain ${banned}`);
  }
  for (const banned of ['writeFileSync', 'mkdirSync', 'renameSync', 'rmSync', 'copyFileSync', 'appendFileSync', 'createWriteStream']) {
    assert.equal(code.includes(banned), false, `extracted module must not write: found ${banned}`);
  }
  assert.deepEqual([...EVIDENCE_CLAIMS.neverEstablishedLocally].sort(),
    ['actualGitCommitProvenance', 'publicationAuthorized', 'trustedCiAttestation']);
});

test('16. publication and deployment authorization are explicitly rejected', (t) => {
  const env = setupEvidence(t);
  env.write({ ...env.record, publicationAuthorized: true });
  assert.deepEqual(verify(env), { ok: false, reason: 'R31_INVALID_POLICY' });
  env.write({ ...env.record, deployAllowed: true });
  assert.deepEqual(verify(env), { ok: false, reason: 'R31_INVALID_POLICY' });
  env.write(env.record);
  const clean = verify(env);
  assert.equal(clean.ok, true, clean.reason);
  assert.equal(clean.claims.notEstablished.publicationAuthorized, false);
  assert.equal(clean.claims.notEstablished.actualGitCommitProvenance, 'NOT_ESTABLISHED');
  assert.equal(clean.claims.notEstablished.trustedCiAttestation, 'NOT_ESTABLISHED');
});
