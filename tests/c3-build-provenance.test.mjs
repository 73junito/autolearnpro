// C3-R29 — build provenance tests. Disposable temporary fixtures only.
// Run with: node --test tests/c3-build-provenance.test.mjs
import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {
  proposeBuildAttestation, verifyBuildPair, CLAIM_CLASSES,
} from '../infrastructure/c3/library/build-provenance-r21.mjs';
import { createTargetPolicy, TARGET_TIERS } from '../infrastructure/c3/library/target-policy.mjs';
import { materializeGeneration } from '../infrastructure/c3/library/library-generation-r20.mjs';
import { inspectLibraryPair } from '../infrastructure/c3/library/library-pair-reader.mjs';
import { assertTargetsApproved } from '../infrastructure/c3/library/library-pair-recovery.mjs';

const TARGETS = ['specs/asset-library.json', 'specs/asset-library.generated.js'];
const VALUE = { version: 1, generation: 'gen-0001', assets: [{ id: 'a1' }, { id: 'a2' }] };
const COMMIT_A = 'a'.repeat(64);
const COMMIT_B = 'b'.repeat(64);
const ARTIFACT = 'c'.repeat(64);

const moduleText = (value) => [
  '// Generated by scripts/validate-asset-library.mjs from specs/asset-library.json.',
  '// Do not edit by hand: run `node scripts/validate-asset-library.mjs --build`.',
  `const library = ${JSON.stringify(value, null, 2)};`,
  '', 'export default library;', '',
].join('\n');

function tmp(t, prefix = 'c3-r29-') {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), prefix));
  t.after(() => fs.rmSync(dir, { recursive: true, force: true }));
  return dir;
}

// Real R28 generation evidence produced inside a real R28 temporary policy.
function setup(t) {
  const sourceRoot = tmp(t, 'c3-r29-src-');
  fs.mkdirSync(path.join(sourceRoot, 'specs'), { recursive: true });
  fs.writeFileSync(path.join(sourceRoot, TARGETS[0]), JSON.stringify(VALUE, null, 2));
  fs.writeFileSync(path.join(sourceRoot, TARGETS[1]), moduleText(VALUE));
  const outputRoot = tmp(t, 'c3-r29-out-');
  const policy = createTargetPolicy({ tier: TARGET_TIERS.TEMPORARY, rootDir: outputRoot, targets: TARGETS });
  const made = materializeGeneration({ policy, sourceRoot, outputRoot, enabled: true });
  return { sourceRoot, outputRoot, policy, generationDir: made.output, generationId: made.generationId };
}

function records(env, sourceCommit = COMMIT_A) {
  const base = { policy: env.policy, generationDir: env.generationDir, sourceCommit, artifactSha256: ARTIFACT };
  return {
    catalog: proposeBuildAttestation({ ...base, surface: 'catalog', buildId: 'catalog-build-1' }),
    worker: proposeBuildAttestation({ ...base, surface: 'cloudflare-worker', buildId: 'worker-build-1' }),
  };
}

function snapshot(root) {
  const out = [];
  const walk = (dir) => {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const abs = path.join(dir, entry.name);
      if (entry.isDirectory()) { out.push(['d', path.relative(root, abs)]); walk(abs); }
      else { const s = fs.statSync(abs); out.push(['f', path.relative(root, abs), s.size, s.mtimeMs]); }
    }
  };
  walk(root);
  return out.sort((a, b) => String(a[1]).localeCompare(String(b[1])));
}

test('1. valid temporary generation evidence yields a verified pair', (t) => {
  const env = setup(t);
  const { catalog, worker } = records(env);
  const result = verifyBuildPair({ ...env, catalog, worker });

  assert.equal(result.ok, true);
  assert.equal(result.reason, null);
  assert.match(result.pairId, /^[a-f0-9]{64}$/);
  assert.equal(result.pair.generationId, env.generationId);
  assert.equal(result.pair.sourceCommit, COMMIT_A);
  assert.equal(result.pair.schema, 'alp-c3-r21-pair-v1');
});

test('2. catalog and Worker records carry the same generation identifier', (t) => {
  const env = setup(t);
  const { catalog, worker } = records(env);
  assert.equal(catalog.generationId, worker.generationId);
  assert.equal(catalog.generationId, env.generationId);
  assert.equal(catalog.libraryFile, TARGETS[0]);
  assert.equal(worker.libraryFile, TARGETS[1]);
  assert.notEqual(catalog.librarySha256, worker.librarySha256);
});

test('3. a mismatched generation identifier is refused', (t) => {
  const env = setup(t);
  const { catalog, worker } = records(env);
  const forged = { ...catalog, generationId: 'd'.repeat(64) };
  assert.deepEqual(verifyBuildPair({ ...env, catalog: forged, worker }), { ok: false, reason: 'R21_GENERATION_MISMATCH' });
});

test('4. artifact hashes are asserted, not verified, and the contract states it', (t) => {
  const env = setup(t);
  const { catalog, worker } = records(env);
  const result = verifyBuildPair({ ...env, catalog, worker });
  assert.equal(result.pair.catalogArtifactSha256, ARTIFACT);
  assert.equal(result.pair.workerArtifactSha256, ARTIFACT);
  assert.ok(result.claims.assertedByCaller.includes('artifactSha256'));
  assert.ok(!result.claims.verifiedFromEvidence.includes('artifactSha256'));
  assert.throws(
    () => proposeBuildAttestation({ policy: env.policy, generationDir: env.generationDir, surface: 'catalog', buildId: 'x', sourceCommit: COMMIT_A, artifactSha256: 'not-a-hash' }),
    /R21_INVALID_BUILD_METADATA/,
  );
  assert.throws(
    () => proposeBuildAttestation({ policy: env.policy, generationDir: env.generationDir, surface: 'tarball', buildId: 'x', sourceCommit: COMMIT_A, artifactSha256: ARTIFACT }),
    /R21_INVALID_BUILD_METADATA/,
  );
});

test('5. missing or malformed provenance records are refused', (t) => {
  const env = setup(t);
  const { catalog, worker } = records(env);
  assert.deepEqual(verifyBuildPair({ ...env, catalog: null, worker }), { ok: false, reason: 'R21_INVALID_SHAPE' });
  assert.deepEqual(verifyBuildPair({ ...env, catalog, worker: undefined }), { ok: false, reason: 'R21_INVALID_SHAPE' });
  assert.deepEqual(verifyBuildPair({ ...env, catalog: [catalog], worker }), { ok: false, reason: 'R21_INVALID_SHAPE' });
  const missing = { ...catalog };
  delete missing.librarySha256;
  assert.deepEqual(verifyBuildPair({ ...env, catalog: missing, worker }), { ok: false, reason: 'R21_INVALID_SHAPE' });
  const wrongSchema = { ...catalog, schema: 'alp-something-else' };
  assert.deepEqual(verifyBuildPair({ ...env, catalog: wrongSchema, worker }), { ok: false, reason: 'R21_INVALID_POLICY' });
});

test('6-7. modified catalog or Worker artifacts invalidate the generation', (t) => {
  const env = setup(t);
  const { catalog, worker } = records(env);
  const catalogFile = path.join(env.generationDir, TARGETS[0]);
  const original = fs.readFileSync(catalogFile);
  fs.writeFileSync(catalogFile, 'modified');
  assert.deepEqual(verifyBuildPair({ ...env, catalog, worker }), { ok: false, reason: 'R21_GENERATION_UNVERIFIED' });
  fs.writeFileSync(catalogFile, original);

  const workerFile = path.join(env.generationDir, TARGETS[1]);
  const workerOriginal = fs.readFileSync(workerFile);
  fs.writeFileSync(workerFile, 'modified');
  assert.deepEqual(verifyBuildPair({ ...env, catalog, worker }), { ok: false, reason: 'R21_GENERATION_UNVERIFIED' });
  fs.writeFileSync(workerFile, workerOriginal);

  assert.equal(verifyBuildPair({ ...env, catalog, worker }).ok, true, 'restoring the bytes must restore the pair');
});

test('8. provenance identifiers are deterministic', (t) => {
  const env = setup(t);
  const { catalog, worker } = records(env);
  const first = verifyBuildPair({ ...env, catalog, worker });
  const second = verifyBuildPair({ ...env, catalog, worker });
  assert.equal(first.pairId, second.pairId);
  assert.deepEqual(first.pair, second.pair);

  // A different asserted commit produces a different pair id, because the assertion is part of the pair.
  const other = records(env, COMMIT_B);
  const third = verifyBuildPair({ ...env, ...other });
  assert.equal(third.ok, true);
  assert.notEqual(third.pairId, first.pairId);
});

test('9-10. forged verification and attestation claims are refused', (t) => {
  const env = setup(t);
  const { catalog, worker } = records(env);
  for (const flag of ['sourceCommitVerified', 'ciAttested', 'publicationAuthorized', 'deployAllowed']) {
    const forged = { ...catalog, [flag]: true };
    assert.deepEqual(
      verifyBuildPair({ ...env, catalog: forged, worker }),
      { ok: false, reason: 'R21_INVALID_POLICY' },
      `${flag}:true must be refused`,
    );
  }
  // The module can never emit a true flag itself.
  for (const flag of CLAIM_CLASSES.neverLocallyVerifiable) {
    assert.equal(catalog[flag], false);
    assert.equal(worker[flag], false);
  }
});

test('11. invalid generation locations and policies are refused', (t) => {
  const env = setup(t);
  const { catalog, worker } = records(env);
  const outside = tmp(t, 'c3-r29-outside-');

  assert.deepEqual(verifyBuildPair({ generationDir: env.generationDir, catalog, worker }), { ok: false, reason: 'R21_POLICY_INVALID' });
  assert.deepEqual(
    verifyBuildPair({ policy: { tier: 'temporary', rootDir: process.cwd(), targets: TARGETS, publicationAuthorized: false }, generationDir: env.generationDir, catalog, worker }),
    { ok: false, reason: 'R21_POLICY_INVALID' },
  );
  assert.deepEqual(
    verifyBuildPair({ ...env, generationDir: outside, catalog, worker }),
    { ok: false, reason: 'R21_GENERATION_OUTSIDE_POLICY' },
  );
  assert.deepEqual(
    verifyBuildPair({ ...env, generationDir: path.join(env.outputRoot, 'does-not-exist'), catalog, worker }),
    { ok: false, reason: 'R21_GENERATION_UNAVAILABLE' },
  );
});

test('12. staging and production authorization are refused outright', (t) => {
  const env = setup(t);
  const { catalog, worker } = records(env);
  assert.throws(() => createTargetPolicy({ tier: 'production', rootDir: env.outputRoot, targets: TARGETS }), /R28_PRODUCTION_NOT_AUTHORIZED/);
  assert.throws(() => createTargetPolicy({ tier: 'staging', rootDir: env.outputRoot, targets: TARGETS }), /R28_STAGING_NOT_AUTHORIZED/);

  const forgedProduction = { tier: 'production', rootDir: env.outputRoot, targets: TARGETS, publicationAuthorized: false };
  assert.deepEqual(verifyBuildPair({ policy: forgedProduction, generationDir: env.generationDir, catalog, worker }), { ok: false, reason: 'R21_POLICY_INVALID' });
  assert.throws(
    () => proposeBuildAttestation({ policy: forgedProduction, generationDir: env.generationDir, surface: 'catalog', buildId: 'x', sourceCommit: COMMIT_A, artifactSha256: ARTIFACT }),
    /R28_PRODUCTION_NOT_AUTHORIZED/,
  );
});

test('13. missing or inconsistent generation manifests are refused', (t) => {
  const env = setup(t);
  const { catalog, worker } = records(env);
  const manifest = path.join(env.generationDir, 'generation.json');
  const original = fs.readFileSync(manifest);
  fs.rmSync(manifest);
  assert.deepEqual(verifyBuildPair({ ...env, catalog, worker }), { ok: false, reason: 'R21_GENERATION_UNVERIFIED' });
  fs.writeFileSync(manifest, '{ not json');
  assert.deepEqual(verifyBuildPair({ ...env, catalog, worker }), { ok: false, reason: 'R21_GENERATION_UNVERIFIED' });
  fs.writeFileSync(manifest, original);
  assert.equal(verifyBuildPair({ ...env, catalog, worker }).ok, true);
});

test('14. provenance verification performs no persistent filesystem changes', (t) => {
  const env = setup(t);
  const before = [snapshot(env.outputRoot), snapshot(env.sourceRoot)];
  const { catalog, worker } = records(env);
  verifyBuildPair({ ...env, catalog, worker });
  verifyBuildPair({ ...env, catalog, worker: { ...worker, ciAttested: true } });
  assert.deepEqual(snapshot(env.outputRoot), before[0]);
  assert.deepEqual(snapshot(env.sourceRoot), before[1]);
});

test('15. no deployment or publication authority is ever produced', (t) => {
  const env = setup(t);
  const { catalog, worker } = records(env);
  const result = verifyBuildPair({ ...env, catalog, worker });
  for (const flag of ['publicationAuthorized', 'deployAllowed', 'sourceCommitVerified', 'ciAttested']) {
    assert.equal(result.pair[flag], false, `${flag} must be false on the verified pair`);
  }
  for (const key of ['published', 'url', 'deployment', 'releaseAuthorized']) {
    assert.equal(Object.prototype.hasOwnProperty.call(result, key), false);
  }
  assert.deepEqual([...CLAIM_CLASSES.neverLocallyVerifiable].sort(), ['ciAttested', 'deployAllowed', 'publicationAuthorized', 'sourceCommitVerified']);
});

test('16. interoperability with R26, R27 and R28', (t) => {
  const env = setup(t);
  // R27 accepts the source pair the generation was built from.
  assert.equal(inspectLibraryPair({ rootDir: env.sourceRoot, allowedTargets: TARGETS }).ok, true);
  // R26 authorization governs the pair order used for the surfaces.
  assert.deepEqual([...assertTargetsApproved(TARGETS)], TARGETS);
  // R28 produced the evidence and still refuses non-temporary tiers.
  assert.equal(env.generationId.length, 64);
  assert.throws(() => createTargetPolicy({ tier: 'staging', rootDir: env.outputRoot, targets: TARGETS }), /R28_STAGING_NOT_AUTHORIZED/);
  // The provenance module never hand-builds a generation; it consumes R28 evidence.
  const { catalog, worker } = records(env);
  assert.equal(catalog.libraryFile, TARGETS[0]);
  assert.equal(verifyBuildPair({ ...env, catalog, worker }).pair.generationId, env.generationId);
});

test('17. containment is re-derived at the operation: a swapped directory is caught', (t) => {
  const env = setup(t);
  const { catalog, worker } = records(env);
  const outside = tmp(t, 'c3-r29-swap-');
  const linked = path.join(env.outputRoot, 'linked-generation');
  try {
    fs.symlinkSync(outside, linked, 'junction');
  } catch {
    t.skip('host cannot create a directory link');
    return;
  }
  // The policy object is unchanged and was valid when created; the filesystem moved underneath it.
  assert.deepEqual(
    verifyBuildPair({ ...env, generationDir: linked, catalog, worker }),
    { ok: false, reason: 'R21_GENERATION_OUTSIDE_POLICY' },
  );
  assert.throws(
    () => proposeBuildAttestation({ policy: env.policy, generationDir: linked, surface: 'catalog', buildId: 'x', sourceCommit: COMMIT_A, artifactSha256: ARTIFACT }),
    /R21_GENERATION_OUTSIDE_POLICY/,
  );
});
