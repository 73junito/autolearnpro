// C3-R27: isolated port of the C3-R19 consistent library-pair reader.
//
// SOURCE BASELINE (reviewed, unmodified): lib/assets/library-pair-reader.mjs in the staging workspace
//   sha256 9cd129391dd4e5af567836cacaf4957c6902362d9327bb54f19ff4017bc72c39 (50 lines)
//
// READ-ONLY. This module writes nothing, deletes nothing, takes no lock, edits no journal, and never
// calls recovery. It answers one question - is the approved pair consistent right now - and fails closed.
// NODE-ONLY: never import from the Cloudflare Worker, a request handler, or a route.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
// R27 ADAPTATION 1 - authorization is delegated to the C3-R26 module, so the reader cannot hold a
// second, weaker copy of the rule. There is no local fallback target list.
import { JOURNAL_NAME, LOCK_NAME, assertTargetsApproved } from './library-pair-recovery.mjs';

const checksum = (b) => crypto.createHash('sha256').update(b).digest('hex');
const safeJson = (s) => { try { return JSON.parse(s); } catch { return null; } };
const within = (root, child) => child.toLowerCase().startsWith((root + path.sep).toLowerCase());

// Unchanged from the source. Reconstructs the entire expected module text and compares bytes, so extra
// executable statements appended after the export cannot pass. The two header strings and the
// `scripts/validate-asset-library.mjs` / `specs/asset-library.json` references are part of the GENERATED
// FORMAT CONTRACT, not target authorization - they must stay byte-identical or every real library fails.
function workerLibrary(source) {
  const start = source.indexOf('const library = ');
  const end = source.lastIndexOf(';\n\nexport default library;');
  if (start < 0 || end < start) return null;
  const prefix = source.slice(0, start).trim();
  if (!prefix.startsWith('// Generated by scripts/validate-asset-library.mjs')) return null;
  const json = source.slice(start + 'const library = '.length, end);
  const value = safeJson(json);
  if (!value) return null;
  // Require the complete deterministic source; parsing a prefix alone permits
  // extra executable statements after the expected export.
  const expected = [
    '// Generated by scripts/validate-asset-library.mjs from specs/asset-library.json.',
    '// Do not edit by hand: run `node scripts/validate-asset-library.mjs --build`.',
    `const library = ${JSON.stringify(value, null, 2)};`,
    '', 'export default library;', '',
  ].join('\n');
  return source === expected ? value : null;
}

const canonical = (o) => JSON.stringify(o);

// R27 ADAPTATION 2 - a "pair" of two paths where one is an ancestor of the other is not a pair.
// Duplicates are already refused by assertTargetsApproved; this rejects the nesting case it cannot see.
export function assertDistinctTargets(targets) {
  const list = targets.map((t) => t.replaceAll('\\', '/').replace(/\/+$/, ''));
  for (let i = 0; i < list.length; i++) {
    for (let j = 0; j < list.length; j++) {
      if (i !== j && list[j].startsWith(list[i] + '/')) throw Error('R19_TARGET_CONFLICT');
    }
  }
  return targets;
}

// R27 ADAPTATION 3 - containment is checked for every target parent before any read. The source applied
// lstat only to the target file, so a linked `specs/` directory was followed without question.
function escapeReason(root, paths) {
  for (const target of paths) {
    const parentDir = path.dirname(target);
    // An absent parent is reported by the existence check below, not as an escape.
    if (!fs.existsSync(parentDir)) continue;
    if (!within(root, fs.realpathSync(parentDir))) return 'R19_PATH_ESCAPE';
  }
  return null;
}

export function inspectLibraryPair({ rootDir, allowedTargets } = {}) {
  if (typeof rootDir !== 'string') return { ok: false, reason: 'R19_ROOT_REQUIRED' };
  // Authorization precedes every filesystem call, including realpathSync of the root.
  let approved;
  try {
    approved = assertDistinctTargets(assertTargetsApproved(allowedTargets));
  } catch {
    return { ok: false, reason: 'R19_TARGETS_NOT_APPROVED' };
  }
  let root;
  try {
    root = fs.realpathSync(rootDir);
  } catch {
    return { ok: false, reason: 'R19_ROOT_UNAVAILABLE' };
  }
  const specs = path.join(root, 'specs');
  if (fs.existsSync(path.join(specs, JOURNAL_NAME))) return { ok: false, reason: 'R19_PENDING_JOURNAL' };
  if (fs.existsSync(path.join(specs, LOCK_NAME))) return { ok: false, reason: 'R19_WRITER_LOCK_PRESENT' };
  const paths = approved.map((x) => path.join(root, x));
  try {
    const escaped = escapeReason(root, paths);
    if (escaped) return { ok: false, reason: escaped };
    if (paths.some((x) => !fs.existsSync(x) || fs.lstatSync(x).isSymbolicLink())) {
      return { ok: false, reason: 'R19_MISSING_OR_SYMLINK' };
    }
    const first = paths.map((x) => fs.readFileSync(x));
    const json = safeJson(first[0].toString('utf8')), module = workerLibrary(first[1].toString('utf8'));
    if (!json || !module) return { ok: false, reason: 'R19_INVALID_DOCUMENT' };
    if (canonical(json) !== canonical(module)) return { ok: false, reason: 'R19_LIBRARY_MISMATCH' };
    // Detect changes that occur while reading, or pending transaction evidence that appears.
    const second = paths.map((x) => fs.readFileSync(x));
    if (first.some((b, i) => checksum(b) !== checksum(second[i]))) return { ok: false, reason: 'R19_UNSTABLE_READ' };
    if (fs.existsSync(path.join(specs, JOURNAL_NAME)) || fs.existsSync(path.join(specs, LOCK_NAME))) {
      return { ok: false, reason: 'R19_TRANSACTION_STARTED_DURING_READ' };
    }
    return {
      ok: true,
      reason: null,
      hashes: paths.map((x, i) => ({ path: approved[i], sha256: checksum(first[i]) })),
      assetCount: Array.isArray(json.assets) ? json.assets.length : null,
    };
  } catch {
    return { ok: false, reason: 'R19_READ_FAILED' };
  }
}
